#!/usr/bin/env python3
"""
Generate the demo INPUT artefacts for the Hueline Service Agent order-capture journey.

All three files dictate the SAME eight-line order as data pack section 7.3, so every
downstream total reconciles: 8 products, 73 units, Rs 2,82,500 (row 5 = the flagged
"confirm" line - "gloss enamel brown" is ambiguous between the Brown and Golden-Brown
4 L variants). See the demo board sections 7.3 / 7.4.

  dealer_handwritten_list.png   path A1 (image upload) - photo of the handwritten pad
  order_sheet_30sep.pdf         path A3 (file upload)   - printed/PDF order sheet
  dealer_order_note.m4a         path A2 (voice note)    - generated by the sibling .sh

Run:  python3 generate_demo_files.py
"""
import os
from PIL import Image, ImageDraw, ImageFont

OUT = os.path.dirname(os.path.abspath(__file__))

# ---- data pack 7.3 : "as written on the pad" (deliberately untidy, abbreviated) ----
HANDWRITTEN_LINES = [
    "Fieldcoat TE1 20L  -  6",
    "Fieldcoat Supwhite 20L  -  12",
    "Fieldcoat TE1 4L  -  20",
    "Glosscoat gloss black 4L  -  4",
    "gloss enamel brown 4L  -  15",
    "Glosscoat gloss black 1L  -  8",
    "wall putty 20kg  -  5",
    "Hueline wall putty 5kg  -  3",
]

# ---- data pack 7.2/7.3 : slightly-untidy names for the file path so matching shows work ----
# (Product, Pack, Qty)
SHEET_ROWS = [
    ("Fieldcoat Emulsion TE1", "20 L", 6),
    ("Fieldcoat Emulsion Supwhite", "20 L", 12),
    ("Fieldcoat Emulsion TE1", "4 L", 20),
    ("Glosscoat Gloss Enamel Black", "4 L", 4),
    ("Glosscoat Gloss Enamel Brown", "4 L", 15),
    ("Glosscoat Gloss Enamel Black", "1 L", 8),
    ("Smoothset Wall Putty White", "20 KG", 5),
    ("Hueline Wall Putty White", "5 KG", 3),
]

HAND_FONT = "/System/Library/Fonts/Supplemental/Bradley Hand Bold.ttf"


def make_handwritten_png():
    """Photo of a handwritten list on a lined pad (path A1 - primary demo path)."""
    W, H = 1200, 1600
    # warm off-white 'paper'
    img = Image.new("RGB", (W, H), (250, 247, 236))
    d = ImageDraw.Draw(img)

    # ruled lines + red margin, like a shop order pad
    line_gap = 150
    top = 360
    for i in range(9):
        y = top + i * line_gap
        d.line([(80, y), (W - 60, y)], fill=(176, 196, 222), width=2)
    d.line([(170, 120), (170, H - 60)], fill=(214, 150, 150), width=3)

    title_font = ImageFont.truetype(HAND_FONT, 78)
    body_font = ImageFont.truetype(HAND_FONT, 62)

    ink = (28, 42, 92)  # blue-black ballpoint
    d.text((200, 170), "Order - Wed 30/9", font=title_font, fill=ink)

    import random
    random.seed(7)  # stable 'handwriting' jitter run to run
    for i, line in enumerate(HANDWRITTEN_LINES):
        y = top + i * line_gap - 86
        x = 200 + random.randint(-6, 8)
        # draw each line on its own small canvas so we can rotate it a touch
        tmp = Image.new("RGBA", (W, 140), (0, 0, 0, 0))
        td = ImageDraw.Draw(tmp)
        td.text((0, 20), f"{i + 1}.  {line}", font=body_font, fill=ink + (255,))
        tmp = tmp.rotate(random.uniform(-1.6, 1.6), expand=False, resample=Image.BICUBIC)
        img.paste(tmp, (x, y), tmp)

    path = os.path.join(OUT, "dealer_handwritten_list.png")
    img.save(path, "PNG")
    print("wrote", path)


def make_order_sheet_pdf():
    """Printed order sheet (path A3 - 'boring but real' file-upload path)."""
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.units import mm
    from reportlab.lib import colors
    from reportlab.platypus import (SimpleDocTemplate, Table, TableStyle,
                                    Paragraph, Spacer)
    from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle

    path = os.path.join(OUT, "order_sheet_30sep.pdf")
    doc = SimpleDocTemplate(path, pagesize=A4,
                            topMargin=20 * mm, bottomMargin=20 * mm,
                            leftMargin=22 * mm, rightMargin=22 * mm)
    styles = getSampleStyleSheet()
    h = ParagraphStyle("h", parent=styles["Title"], fontSize=18, spaceAfter=2)
    sub = ParagraphStyle("sub", parent=styles["Normal"], fontSize=10,
                         textColor=colors.HexColor("#555555"))

    story = [
        Paragraph("Lakeview Colour &amp; Hardware", h),
        Paragraph("Weekly order &nbsp;·&nbsp; Dealer HL-PUN-04417 &nbsp;·&nbsp; "
                  "Pune West · Kothrud &nbsp;·&nbsp; Wed 30 Sep 2026", sub),
        Spacer(1, 10 * mm),
    ]

    data = [["#", "Product", "Pack", "Qty"]]
    units = 0
    for i, (name, pack, qty) in enumerate(SHEET_ROWS, 1):
        data.append([str(i), name, pack, str(qty)])
        units += qty
    data.append(["", "Total", "", str(units)])

    tbl = Table(data, colWidths=[12 * mm, 95 * mm, 25 * mm, 20 * mm])
    tbl.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#C8102E")),  # brand red
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 11),
        ("ALIGN", (0, 0), (0, -1), "CENTER"),
        ("ALIGN", (3, 0), (3, -1), "CENTER"),
        ("ROWBACKGROUNDS", (0, 1), (-1, -2), [colors.white, colors.HexColor("#F4F4F4")]),
        ("LINEBELOW", (0, 0), (-1, 0), 0.5, colors.white),
        ("LINEABOVE", (0, -1), (-1, -1), 0.75, colors.HexColor("#C8102E")),
        ("FONTNAME", (0, -1), (-1, -1), "Helvetica-Bold"),
        ("TOPPADDING", (0, 0), (-1, -1), 7),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 7),
        ("GRID", (0, 0), (-1, -2), 0.25, colors.HexColor("#DDDDDD")),
    ]))
    story.append(tbl)
    story.append(Spacer(1, 8 * mm))
    story.append(Paragraph(
        "8 lines &nbsp;·&nbsp; 73 units. Please deliver to Bhosari depot. "
        "— Anil Verma", sub))
    doc.build(story)
    print("wrote", path)


if __name__ == "__main__":
    make_handwritten_png()
    make_order_sheet_pdf()
